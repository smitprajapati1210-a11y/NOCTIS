import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";

async function files(dir) {
  const result = [];
  for (const item of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, item.name);
    if (item.isDirectory()) result.push(...(await files(path)));
    else if (item.name !== "sw.js") result.push(path);
  }
  return result;
}
const paths = await files("dist");
const digest = createHash("sha256");
for (const path of paths.sort()) digest.update(await readFile(path));
const cache = `noctis-${digest.digest("hex").slice(0, 12)}`;
const urls = ["/", ...paths.map((p) => `/${relative("dist", p)}`)];
await writeFile(
  "dist/sw.js",
  `// Generated by scripts/build-sw.mjs. Journal data is never cached here.\nconst CACHE = ${JSON.stringify(cache)};\nconst ASSETS = ${JSON.stringify(urls)};\nself.addEventListener('install', event => { event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS))); });\nself.addEventListener('activate', event => { event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('noctis-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });\nself.addEventListener('fetch', event => { const url = new URL(event.request.url); if (event.request.method !== 'GET' || url.origin !== self.location.origin) return; if (event.request.mode === 'navigate') { event.respondWith(fetch(event.request).catch(() => caches.match('/index.html'))); return; } if (ASSETS.includes(url.pathname)) event.respondWith(caches.match(event.request).then(hit => hit || fetch(event.request))); });\n`,
);
console.log(`Offline app shell generated (${urls.length} files, ${cache}).`);
